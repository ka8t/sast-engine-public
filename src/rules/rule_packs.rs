    #[test]
    fn test_pack_with_tampered_manifest_rejected_wholesale() {
        let root = temp_dir();
        let pack_dir = root.join("test-pack");
        build_valid_pack(&pack_dir, RULE_SOURCE);
        // Alters the manifest AFTER signing (changes `pack_id`) — the
        // signature no longer matches the actual content.
        let manifest_path = pack_dir.join("manifest.json");
        let mut manifest: Value =
            serde_json::from_str(&std::fs::read_to_string(&manifest_path).unwrap()).unwrap();
        manifest["pack_id"] = Value::String("tampered".to_string());
        std::fs::write(&manifest_path, serde_json::to_string(&manifest).unwrap()).unwrap();

        let (rules, errors) = load_update_packs_with_key(&root, &test_public_key_hex());

        assert!(rules.is_empty(), "le pack entier doit être rejeté");
        assert_eq!(errors.len(), 1);
        assert!(
            errors[0].1.contains("signature"),
            "message inattendu : {}",
            errors[0].1
        );
        std::fs::remove_dir_all(&root).ok();
    }

    #[test]
    fn test_pack_with_tampered_rule_rejected_alone_rest_kept() {
        let root = temp_dir();
        let pack_dir = root.join("test-pack");
        write(&pack_dir, "rules/rule_a.sca", RULE_SOURCE.as_bytes());
        let other_rule = "rule pack_rule_b\n  language  python\n  category  security\n  severity  HIGH\n  match\n    pattern  PACK_MARKER_B\n    scope    line\n  end\nend\n";
        write(&pack_dir, "rules/rule_b.sca", other_rule.as_bytes());
        let manifest = serde_json::json!({
            "pack_id": "test-pack",
            "rules": [
                {"path": "rule_a.sca", "sha256": sha256_hex(RULE_SOURCE.as_bytes())},
                {"path": "rule_b.sca", "sha256": sha256_hex(other_rule.as_bytes())},
            ],
        })
        .as_object()
        .unwrap()
        .clone();
        let signed = sign_manifest(&manifest);
        write(
            &pack_dir,
            "manifest.json",
            serde_json::to_string(&Value::Object(signed))
                .unwrap()
                .as_bytes(),
        );
        // Alters rule_a AFTER the manifest is signed — its hash no
        // longer matches, but the manifest itself remains valid.
        write(
            &pack_dir,
            "rules/rule_a.sca",
            b"altered content, no longer matches its declared hash",
        );

        let (rules, errors) = load_update_packs_with_key(&root, &test_public_key_hex());

        assert_eq!(rules.len(), 1, "seule rule_b doit rester chargée");
        assert_eq!(
            rules[0].get("id").and_then(Value::as_str),
            Some("pack_rule_b")
        );
        assert_eq!(errors.len(), 1);
        assert!(
            errors[0].1.contains("hash SHA-256 divergent"),
            "message inattendu : {}",
            errors[0].1
        );
        std::fs::remove_dir_all(&root).ok();
    }

